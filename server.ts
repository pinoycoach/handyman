// 3. IMAGE GENERATION & EDITING (gemini-nano-banana-2.1)
// ==========================================
app.post('/api/image/generate-or-edit', async (req: Request, res: Response) => {
  try {
    const { prompt, baseImage, aspectRatio = '1:1', imageSize = '1K', useSearch = false } = req.body;
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required.' });
    }

    const ai = getAiClient();
    const parts: any[] = [];

    if (baseImage?.data && baseImage?.mimeType) {
      parts.push({
        inlineData: {
          data: baseImage.data,
          mimeType: baseImage.mimeType,
        },
      });
    }
    parts.push({ text: prompt });

    const config: any = {
      imageConfig: {
        aspectRatio: aspectRatio || '1:1',
        imageSize: imageSize || '1K',
      },
    };

    if (useSearch) {
      config.tools = [
        {
          googleSearch: {
            searchTypes: {
              webSearch: {},
              imageSearch: {},
            },
          },
        },
      ];
    }

    const response = await ai.models.generateContent({
      model: 'gemini-nano-banana-2.1',
      contents: { parts },
      config,
    });

    let imageUrl: string | null = null;
    let textOutput: string | null = null;

    const candidateParts = response.candidates?.[0]?.content?.parts || [];
    for (const part of candidateParts) {
      if (part.inlineData?.data) {
        const mime = part.inlineData.mimeType || 'image/png';
        imageUrl = `data:${mime};base64,${part.inlineData.data}`;
      } else if (part.text) {
        textOutput = part.text;
      }
    }

    if (!imageUrl) {
      return res.status(500).json({ error: 'No image was returned from Gemini Nano Banana 2.1.' });
    }

    return res.json({
      imageUrl,
      text: textOutput,
      model: 'gemini-nano-banana-2.1',
    });
  } catch (error: any) {
    console.error('Image generation/edit error:', error);
    return res.status(500).json({ error: error.message || 'Failed to generate or edit image.' });
  }
});

