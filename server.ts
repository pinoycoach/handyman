// 2. MUSIC GENERATION (lyria-3-clip-preview / lyria-3-pro-preview)
// ==========================================
app.post('/api/music/generate', async (req: Request, res: Response) => {
  try {
    const { prompt, model = 'lyria-3-clip-preview', image } = req.body;
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required for music generation.' });
    }

    const ai = getAiClient();
    const selectedModel = model === 'lyria-3-pro-preview' ? 'lyria-3-pro-preview' : 'lyria-3-clip-preview';

    let contents: any;
    if (image?.data && image?.mimeType) {
      contents = {
        parts: [
          { text: prompt },
          { inlineData: { data: image.data, mimeType: image.mimeType } },
        ],
      };
    } else {
      contents = prompt;
    }

    const responseStream = await ai.models.generateContentStream({
      model: selectedModel,
      contents,
    });

    let audioBase64 = '';
    let lyrics = '';
    let mimeType = 'audio/wav';

    for await (const chunk of responseStream) {
      const parts = chunk.candidates?.[0]?.content?.parts;
      if (!parts) continue;
      for (const part of parts) {
        if (part.inlineData?.data) {
          if (!audioBase64 && part.inlineData.mimeType) {
            mimeType = part.inlineData.mimeType;
          }
          audioBase64 += part.inlineData.data;
        }
        if (part.text && !lyrics) {
          lyrics = part.text;
        }
      }
    }

    if (!audioBase64) {
      return res.status(500).json({ error: 'No audio data was generated by the Lyria music model.' });
    }

    return res.json({
      audioBase64,
      mimeType,
      lyrics,
      model: selectedModel,
    });
  } catch (error: any) {
    console.error('Music generation error:', error);
    return res.status(500).json({ error: error.message || 'Failed to generate music.' });
  }
});

