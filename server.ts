// 1. CHATBOT API (gemini-4-argon / gemini-3.8-flash / gemini-3.1-flash-lite)
// ==========================================
app.post('/api/chat/message', async (req: Request, res: Response) => {
  try {
    const { model = 'gemini-3.8-flash', history = [], message, systemInstruction } = req.body;
    if (!message) {
      return res.status(400).json({ error: 'Message is required.' });
    }

    const ai = getAiClient();
    
    // Validate model selection
    const allowedModels = ['gemini-4-argon', 'gemini-3.8-flash', 'gemini-3.1-flash-lite'];
    const selectedModel = allowedModels.includes(model) ? model : 'gemini-3.8-flash';

    // Format contents with conversation history
    const contents: any[] = [];
    for (const h of history) {
      contents.push({
        role: h.role === 'user' ? 'user' : 'model',
        parts: [{ text: h.text }],
      });
    }
    contents.push({
      role: 'user',
      parts: [{ text: message }],
    });

    const config: any = {
      systemInstruction: systemInstruction || 'You are the DIY & Garden Master Consultant. Provide expert, safe, clear, and step-by-step guidance on carpentry, plumbing, electrical safety, masonry, gardening, pruning, soil health, and tool operation. Offer safety warnings where appropriate.',
    };

    const response = await ai.models.generateContent({
      model: selectedModel,
      contents,
      config,
    });

    const reply = response.text || 'No response generated.';
    return res.json({ text: reply, model: selectedModel });
  } catch (error: any) {
    console.error('Chat error:', error);
    return res.status(500).json({ error: error.message || 'Failed to process chat message.' });
  }
});

