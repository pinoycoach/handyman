// 4. TEXT-TO-VIDEO (gemini-omni-1.1-flash via Interactions API)
// ==========================================
app.post('/api/video/generate-text', async (req: Request, res: Response) => {
  try {
    const { prompt, aspectRatio = '16:9', duration = '5s', resolution = '720p' } = req.body;
    if (!prompt) {
      return res.status(400).json({ error: 'Prompt is required for video generation.' });
    }

    const ai = getAiClient();
    const interaction = await ai.interactions.create(
      {
        model: 'gemini-omni-1.1-flash',
        input: prompt,
        background: false,
        store: false,
        stream: false,
        response_format: {
          type: 'video',
          aspect_ratio: aspectRatio === '9:16' ? '9:16' : '16:9',
          duration: duration === '10s' ? '10s' : '5s',
          resolution: resolution || '720p',
        },
      },
      { timeout: 300000 }
    );

    const videoPart = interaction.output_video;
    if (!videoPart || (!videoPart.data && !videoPart.uri)) {
      return res.status(500).json({ error: 'No video was returned from the Omni Flash Interactions API.' });
    }

    const mimeType = videoPart.mime_type || 'video/mp4';
    const videoUrl = videoPart.data ? `data:${mimeType};base64,${videoPart.data}` : videoPart.uri;

    return res.json({
      videoUrl,
      aspectRatio,
      model: 'gemini-omni-1.1-flash',
    });
  } catch (error: any) {
    console.error('Text-to-video error:', error);
    return res.status(500).json({ error: error.message || 'Failed to generate video from text.' });
  }
});

